import { Brain, AlertCircle } from 'lucide-react';
import type { FullResultDetail, ScoreLevel } from '../types';

interface Props {
  result: FullResultDetail;
}

const SCORE_CONFIG: Record<ScoreLevel, { label: string; bg: string; text: string; border: string; dot: string }> = {
  LOW:      { label: 'Low',      bg: 'bg-emerald-50', text: 'text-emerald-700', border: 'border-emerald-200', dot: 'bg-emerald-400' },
  MODERATE: { label: 'Moderate', bg: 'bg-amber-50',   text: 'text-amber-700',   border: 'border-amber-200',   dot: 'bg-amber-400'   },
  HIGH:     { label: 'High',     bg: 'bg-rose-50',    text: 'text-rose-700',    border: 'border-rose-200',    dot: 'bg-rose-500'    },
};

const CONDITIONS = [
  { key: 'gout_score'   as const, label: 'Gout',              description: 'Uric acid crystal deposition' },
  { key: 'gn_score'     as const, label: 'Glomerulonephritis', description: 'Glomerular inflammation'       },
  { key: 'nephro_score' as const, label: 'Nephrolithiasis',    description: 'Urinary stone formation'       },
];

function ScorePill({ level }: { level: ScoreLevel }) {
  const cfg = SCORE_CONFIG[level];
  return (
    <span className={`inline-flex items-center gap-1.5 rounded-full border px-2.5 py-1 text-xs font-bold ${cfg.bg} ${cfg.text} ${cfg.border}`}>
      <span className={`h-1.5 w-1.5 rounded-full ${cfg.dot}`} />
      {cfg.label}
    </span>
  );
}

function EvidenceList({ items }: { items: string[] }) {
  if (!items.length) return <span className="text-xs text-slate-400 italic">No supporting markers</span>;
  return (
    <ul className="space-y-0.5">
      {items.map((item) => (
        <li key={item} className="flex items-start gap-1.5 text-xs text-slate-600">
          <span className="mt-1 h-1 w-1 shrink-0 rounded-full bg-slate-400" />
          {item}
        </li>
      ))}
    </ul>
  );
}

export function SmartDiagnosisSection({ result }: Props) {
  const sd = result.smart_diagnosis;

  return (
    <div className="rounded-2xl border border-slate-200 bg-white overflow-hidden shadow-sm">
      {/* Header */}
      <div className="flex items-center gap-3 px-5 py-3.5 bg-violet-50 border-b border-violet-100">
        <div className="flex h-7 w-7 items-center justify-center rounded-lg bg-violet-100">
          <Brain className="h-3.5 w-3.5 text-violet-600" />
        </div>
        <div className="flex-1 min-w-0">
          <h3 className="text-xs font-bold text-violet-800 uppercase tracking-widest">Smart Diagnosis</h3>
        </div>
        {sd && (
          <span className="text-[10px] text-violet-400 font-mono">
            Engine v{sd.engine_version}
          </span>
        )}
      </div>

      <div className="p-5">
        {/* Unavailable state */}
        {result.smart_diagnosis_unavailable || !sd ? (
          <div className="flex items-start gap-3 rounded-xl border border-amber-100 bg-amber-50 px-4 py-3">
            <AlertCircle className="h-4 w-4 text-amber-500 shrink-0 mt-0.5" />
            <p className="text-sm text-amber-700">
              Smart Diagnosis engine was unavailable for this specimen. No probability scores were generated.
            </p>
          </div>
        ) : (
          <div className="space-y-4">
            {/* No significant indicators banner */}
            {sd.no_significant_indicators && (
              <div className="rounded-xl border border-emerald-100 bg-emerald-50 px-4 py-2.5 text-sm text-emerald-700 font-medium">
                No significant clinical indicators detected across all conditions.
              </div>
            )}

            {/* Condition rows */}
            <div className="space-y-0 rounded-xl border border-slate-100 overflow-hidden divide-y divide-slate-100">
              {CONDITIONS.map(({ key, label, description }) => {
                const level = sd[key];
                const evidence: string[] = sd.evidence_map?.[key] ?? [];
                return (
                  <div key={key} className="px-4 py-3.5">
                    <div className="flex items-center justify-between mb-2">
                      <div>
                        <p className="text-sm font-semibold text-slate-800">{label}</p>
                        <p className="text-[10px] text-slate-400 mt-0.5">{description}</p>
                      </div>
                      <ScorePill level={level} />
                    </div>
                    {evidence.length > 0 && (
                      <div className="mt-2 pl-2 border-l-2 border-slate-100">
                        <EvidenceList items={evidence} />
                      </div>
                    )}
                  </div>
                );
              })}
            </div>

            {/* Disclaimer */}
            <p className="text-[10px] text-slate-400 leading-relaxed">
              Scores are generated by the UroLens rule engine and are intended as a clinical aid only.
              They do not constitute a diagnosis. Supervisor review is required before release.
            </p>
          </div>
        )}
      </div>
    </div>
  );
}
